// La conversation avec le second d'un projet, lue au transcript que le second
// du desktop reprend (#1413) : ce que le chef a écrit et ce que le second a
// répondu, et rien de ce que Claude Code y range d'autre.
import assert from "node:assert/strict";
import { mkdirSync, realpathSync, utimesSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { test, type TestContext } from "node:test";
import { ConversationIllisible, lireLaConversation, MESSAGES_MAX, messagesDuTranscript, principal, transcriptDuSecond } from "../../src/second/conversation.ts";
import { repertoireTemporaire } from "../outils.ts";

const SESSION = "0b6c1c2e-4f5a-4b7c-9d8e-1f2a3b4c5d6e";
const AUTRE = "7f6e5d4c-3b2a-4190-8f7e-6d5c4b3a2918";

const ligne = (entree: Record<string, unknown>) => `${JSON.stringify({ sessionId: SESSION, isSidechain: false, ...entree })}\n`;
const chef = (content: unknown, at: string, plus: Record<string, unknown> = {}) => ligne({ type: "user", timestamp: at, message: { role: "user", content }, ...plus });
const second = (content: unknown[], at: string, plus: Record<string, unknown> = {}) => ligne({ type: "assistant", timestamp: at, message: { id: `msg_${at}`, role: "assistant", content }, ...plus });

// Ce que Claude Code écrit, en vrai, pour une session ouverte par l'app : la
// commande du rôle, sa mise en garde, ses appels d'outils, sa réflexion.
const TRANSCRIPT = [
  ligne({ type: "queue-operation", operation: "enqueue", timestamp: "2026-10-23T08:00:00.000Z" }),
  chef("Caveat: The messages below were generated by the user while running local commands.", "2026-10-23T08:00:00.001Z", { isMeta: true }),
  chef("<command-message>brigade:po</command-message>\n<command-name>/brigade:po</command-name>", "2026-10-23T08:00:00.002Z"),
  chef([{ type: "text", text: "# The PO role\n…" }], "2026-10-23T08:00:00.003Z", { isMeta: true }),
  second([{ type: "thinking", thinking: "Let me read the queue." }, { type: "tool_use", id: "t1", name: "Bash", input: { command: "npm run rail" } }], "2026-10-23T08:00:01.000Z"),
  chef([{ type: "tool_result", tool_use_id: "t1", content: "#14 TODO" }], "2026-10-23T08:00:02.000Z"),
  second([{ type: "text", text: "Two tickets wait for you." }], "2026-10-23T08:00:03.000Z"),
  second([{ type: "text", text: "**#14** waits for your merge." }], "2026-10-23T08:00:04.000Z"),
  ligne({ type: "attachment", timestamp: "2026-10-23T08:00:05.000Z" }),
  chef("<bash-input>git status</bash-input>", "2026-10-23T08:01:00.000Z"),
  chef("<bash-stdout>nothing to commit</bash-stdout><bash-stderr></bash-stderr>", "2026-10-23T08:01:00.100Z"),
  chef("<local-command-stdout>Compacted</local-command-stdout>", "2026-10-23T08:01:00.200Z"),
  chef("Merge #14 please\n<system-reminder>the date is 2026-10-23</system-reminder>", "2026-10-23T08:02:00.000Z"),
  second([{ type: "text", text: "Sub-agent talk" }], "2026-10-23T08:02:00.500Z", { isSidechain: true }),
  chef("[Request interrupted by user]", "2026-10-23T08:02:01.000Z"),
  chef("This session is being continued from a previous conversation…", "2026-10-23T08:02:02.000Z", { isCompactSummary: true }),
  second([{ type: "text", text: "Merged: https://github.com/acme/brigade/pull/114" }], "2026-10-23T08:02:30.000Z"),
  '{"type":"user","message":{"content":"cut in the mid',
].join("");

test("une conversation est ce que le chef a écrit et ce que le second a répondu, dans l'ordre : ni outils, ni réflexion, ni rappels, ni sous-agents, ni sorties de commande", () => {
  assert.deepEqual(messagesDuTranscript(TRANSCRIPT), [
    { from: "chef", at: "2026-10-23T08:00:00.002Z", text: "/brigade:po" },
    // Deux textes d'affilée, autour d'un appel d'outil, sont une seule réponse.
    { from: "second", at: "2026-10-23T08:00:04.000Z", text: "Two tickets wait for you.\n\n**#14** waits for your merge." },
    { from: "chef", at: "2026-10-23T08:01:00.000Z", text: "!git status" },
    { from: "chef", at: "2026-10-23T08:02:00.000Z", text: "Merge #14 please" },
    { from: "second", at: "2026-10-23T08:02:30.000Z", text: "Merged: https://github.com/acme/brigade/pull/114" },
  ]);
});

function poser(t: TestContext) {
  const racine = repertoireTemporaire(t);
  const claude = join(racine, "claude");
  const dossier = join(racine, "shop");
  mkdirSync(dossier);
  const projet = join(claude, "projects", realpathSync(dossier).replace(/[^a-zA-Z0-9]/g, "-"));
  return { claude, dossier, projet };
}

test("la conversation lue est celle du transcript le plus récent du dossier — celui que `claude --continue` y reprend —, et sa session", (t) => {
  const { claude, dossier, projet } = poser(t);
  assert.deepEqual(lireLaConversation({ claude, dossier }), { session: null, messages: [] }, "un dossier sans session n'a pas encore de conversation");

  mkdirSync(projet, { recursive: true });
  writeFileSync(join(projet, `${AUTRE}.jsonl`), chef("an older thread", "2026-10-20T08:00:00.000Z"));
  writeFileSync(join(projet, `${SESSION}.jsonl`), TRANSCRIPT);
  utimesSync(join(projet, `${AUTRE}.jsonl`), new Date("2026-10-20T08:00:00Z"), new Date("2026-10-20T08:00:00Z"));
  // Ni un sous-répertoire de session, ni ce qui n'est pas un transcript.
  mkdirSync(join(projet, SESSION, "subagents"), { recursive: true });
  writeFileSync(join(projet, "notes.txt"), "");

  const lue = lireLaConversation({ claude, dossier });
  assert.equal(lue.session, SESSION);
  assert.equal(transcriptDuSecond(claude, dossier), join(projet, `${SESSION}.jsonl`));
  assert.deepEqual(lue.messages, messagesDuTranscript(TRANSCRIPT));
  assert.equal(lue.omitted, undefined);
});

test(`une longue session ne rend que ses ${MESSAGES_MAX} derniers messages, et compte ceux d'avant`, (t) => {
  const { claude, dossier, projet } = poser(t);
  mkdirSync(projet, { recursive: true });
  const echanges = Array.from({ length: MESSAGES_MAX }, (_, i) => chef(`question ${i}`, `2026-10-23T08:00:${String(i % 60).padStart(2, "0")}.000Z`) + second([{ type: "text", text: `answer ${i}` }], "2026-10-23T09:00:00.000Z")).join("");
  writeFileSync(join(projet, `${SESSION}.jsonl`), echanges);
  const lue = lireLaConversation({ claude, dossier });
  assert.equal(lue.messages.length, MESSAGES_MAX);
  assert.equal(lue.omitted, MESSAGES_MAX);
  assert.deepEqual(lue.messages.at(-1), { from: "second", at: "2026-10-23T09:00:00.000Z", text: `answer ${MESSAGES_MAX - 1}` });
});

test("un dossier qui n'existe pas ne se lit pas, et le dit en une phrase", (t) => {
  const { claude, dossier } = poser(t);
  assert.throws(() => lireLaConversation({ claude, dossier: join(dossier, "absent") }), (erreur: unknown) => erreur instanceof ConversationIllisible && /^the project's folder .*absent does not exist on this machine$/.test(erreur.message));
});

test("la commande rend la conversation en une ligne JSON — code 0 —, la phrase qui dit pourquoi elle ne se lit pas — code 1 —, et 2 sans dossier", async (t) => {
  const { claude, dossier, projet } = poser(t);
  mkdirSync(projet, { recursive: true });
  writeFileSync(join(projet, `${SESSION}.jsonl`), TRANSCRIPT);
  const jouer = async (args: string[]) => {
    const lignes: string[] = [];
    let code = 0;
    try {
      await principal({ args, env: { CLAUDE_CONFIG_DIR: claude }, dire: (ligne) => lignes.push(ligne), redire: (ligne) => lignes.push(ligne) });
    } catch (sortie) {
      code = (sortie as { code: number }).code;
    }
    return { code, lignes };
  };
  assert.deepEqual(await jouer([dossier]), { code: 0, lignes: [JSON.stringify(lireLaConversation({ claude, dossier }))] });
  const absent = await jouer([join(dossier, "absent")]);
  assert.equal(absent.code, 1);
  assert.match(JSON.parse(absent.lignes[0] ?? "{}").said, /^the second's conversation cannot be read: the project's folder .* does not exist on this machine$/);
  assert.equal((await jouer([])).code, 2);
});
